def require_packed_row_loader_columns(
    column_names: set[str] | tuple[str, ...] | list[str],
) -> None:
    """Raise when a parquet schema is missing the loader's core fixed-width arrays."""

    required_columns: set[str] = set(PACKED_ROWS_LOADER_REQUIRED_COLUMNS)
    missing = sorted(required_columns - set(column_names))
    if missing:
        raise ValueError(
            "Packed-row parquet missing required loader columns: " + ", ".join(missing)
        )


def packed_row_dense_column_is_present(
    row: Mapping[str, Any],
    *,
    column: str,
    row_length: int,
) -> bool:
    """Return True when an optional dense row-local column is present and shape-valid."""

    values = row.get(column)
    if values is None:
        return False
    if isinstance(values, np.ndarray):
        if values.size == 0:
            return False
        if values.size != row_length:
            raise ValueError(
                f"packed row {column} must have length T={row_length}, got {values.size}"
            )
        return True
    if isinstance(values, list):
        if len(values) == 0:
            return False
        if len(values) != row_length:
            raise ValueError(
                f"packed row {column} must have length T={row_length}, got {len(values)}"
            )
        return True
    raise ValueError(
        f"packed row {column} must be a list, numpy array, or absent, "
        f"got {type(values).__name__}"
    )


def resolve_packed_row_valid_token_count(
    row: Mapping[str, Any],
    *,
    row_length: int,
) -> int:
    """Resolve the runtime token-prefix count for one packed row."""

    value = row.get(VALID_TOKEN_COUNT_COLUMN)
    if value is None:
        loss_mask = row.get(LOSS_MASK_COLUMN)
        if (
            not isinstance(loss_mask, (list, np.ndarray))
            or len(loss_mask) != row_length
        ):
            raise ValueError(
                f"packed row {LOSS_MASK_COLUMN} must have length T={row_length}"
            )
        if isinstance(loss_mask, np.ndarray):
            return int((loss_mask > 0).sum())
        return sum(1 for keep in loss_mask if int(keep) > 0)
    try:
        value = int(value)
    except (TypeError, ValueError) as exc:
        raise ValueError(
            f"packed row {VALID_TOKEN_COUNT_COLUMN} must be an integer, got {value!r}"
        ) from exc
    if not 0 <= value <= row_length:
        raise ValueError(
            f"packed row {VALID_TOKEN_COUNT_COLUMN} must be in [0, T={row_length}], got {value}"
        )
    return value


