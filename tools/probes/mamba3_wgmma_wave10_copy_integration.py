def evaluate_guard_contract(contract: dict[str, Any] | None) -> dict[str, Any]:
    if contract is None:
        return {
            "status": "missing_guard_contract",
            "pass": False,
            "failures": ["guard contract must be generated"],
        }

    failures: list[str] = []
    if contract.get("schema") != CONTRACT_SCHEMA:
        failures.append(f"schema must be {CONTRACT_SCHEMA}, got {contract.get('schema')}")

    constants = contract.get("constants")
    if not isinstance(constants, dict):
        failures.append("constants must be present")
        constants = {}
    expected_constants = {
        "logical_tile_count": 12,
        "global_tile_count": 10,
        "local_stage_tile_count": 2,
        "tile_rows": 64,
        "tile_cols": 64,
        "dtype_bytes": 2,
        "row_bytes": 128,
        "tile_bytes": 8192,
        "vector_bytes": 16,
        "vectors_per_row": 8,
        "vectors_per_tile": 512,
        "vectors_per_chunk": 6144,
        "dynamic_smem_bytes": 98304,
    }
    for field, expected in expected_constants.items():
        if constants.get(field) != expected:
            failures.append(f"constants.{field} must be {expected}, got {constants.get(field)}")
    if constants.get("dtype") != "bf16":
        failures.append(f"constants.dtype must be bf16, got {constants.get('dtype')}")
    if constants.get("vector_type") != "uint4":
        failures.append(f"constants.vector_type must be uint4, got {constants.get('vector_type')}")

    layouts = contract.get("expected_data_layouts")
    if not isinstance(layouts, dict):
        failures.append("expected_data_layouts must be present")
        layouts = {}
    tiles = layouts.get("tiles")
    if not isinstance(tiles, list):
        failures.append("expected_data_layouts.tiles must be a list")
        tiles = []
    tile_names = {tile.get("name") for tile in tiles if isinstance(tile, dict)}
    if tile_names != set(wave8.EXPECTED_TILE_NAMES):
        failures.append(f"tiles must cover Wave8 names, got {sorted(tile_names)}")
    if layouts.get("global_source_tiles_per_chunk") != 10:
        failures.append("global_source_tiles_per_chunk must be 10")
    if layouts.get("local_stage_tiles_per_chunk") != 2:
        failures.append("local_stage_tiles_per_chunk must be 2")

    by_name = {tile.get("name"): tile for tile in tiles if isinstance(tile, dict)}
    for transpose_name in ("K_T", "Q_T"):
        proof = by_name.get(transpose_name, {}).get("transpose_layout_proof")
        if not isinstance(proof, dict):
            failures.append(f"{transpose_name}: transpose_layout_proof must be present")
            continue
        if proof.get("vector_compatible") is not True:
            failures.append(f"{transpose_name}: transpose layout must be vector compatible")
        if proof.get("per_column_scalar_scatter") is not False:
            failures.append(f"{transpose_name}: per_column_scalar_scatter must be false")

    guard_conditions = contract.get("guard_conditions")
    if not isinstance(guard_conditions, dict):
        failures.append("guard_conditions must be present")
        guard_conditions = {}
    for section in ("compile_time", "runtime", "layout", "resource", "synchronization"):
        values = guard_conditions.get(section)
        if not isinstance(values, list) or not values:
            failures.append(f"guard_conditions.{section} must be a non-empty list")

    header = contract.get("guard_header")
    if not isinstance(header, dict):
        failures.append("guard_header must be present")
    elif header.get("sha256") != _guard_header_sha256():
        failures.append("guard_header.sha256 must match rendered header")

    api = contract.get("api_sketch")
    if not isinstance(api, dict):
        failures.append("api_sketch must be present")
    elif "runtime_guard_bits" not in api.get("device_guard", ""):
        failures.append("api_sketch.device_guard must name runtime_guard_bits")

    failure_modes = contract.get("failure_modes")
    if not isinstance(failure_modes, list) or len(failure_modes) < 6:
        failures.append("failure_modes must enumerate integration blockers")

    return {
        "status": "pass" if not failures else "fail",
        "pass": not failures,
        "failures": failures,
    }


