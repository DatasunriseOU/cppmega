def _receipt_blockers(
    *,
    alignment_check: dict[str, Any],
    ptxas_ingest: dict[str, Any],
    ptxas_resource_check: dict[str, Any],
    runtime_check: dict[str, Any],
    guard_contract_check: dict[str, Any],
) -> list[str]:
    blockers: list[str] = []
    if not alignment_check["pass"]:
        blockers.extend(f"alignment/layout: {failure}" for failure in alignment_check["failures"])
    if ptxas_ingest.get("status") != "parsed":
        blockers.extend(f"ptxas-ingest: {failure}" for failure in ptxas_ingest.get("failures", []))
    if ptxas_ingest.get("kernel_name") != wave9.PROBE_KERNEL:
        blockers.append(
            f"ptxas-ingest: kernel_name must be {wave9.PROBE_KERNEL}, got {ptxas_ingest.get('kernel_name')}"
        )
    if not ptxas_resource_check["pass"]:
        blockers.extend(f"ptxas-resource: {failure}" for failure in ptxas_resource_check["failures"])
    if not runtime_check["pass"]:
        blockers.extend(f"runtime: {failure}" for failure in runtime_check["failures"])
    if not guard_contract_check["pass"]:
        blockers.extend(f"guard-contract: {failure}" for failure in guard_contract_check["failures"])
    return blockers


def build_receipt(
    *,
    runtime_result: dict[str, Any] | None = None,
    ptxas_ingest: dict[str, Any] | None = None,
    alignment_evidence: dict[str, Any] | None = None,
) -> dict[str, Any]:
    effective_alignment = alignment_evidence or wave8.build_alignment_layout_evidence()
    effective_runtime = runtime_result or wave9._runtime_missing("attach Wave9 runtime probe JSON")
    effective_ptxas = wave9.normalize_ptxas_ingest(ptxas_ingest)

    alignment_check = wave8.evaluate_alignment_layout_evidence(effective_alignment)
    runtime_check = wave9.evaluate_runtime_result(effective_runtime)
    ptxas_resource_check = wave6.evaluate_ptxas_metadata(
        effective_ptxas.get("metadata"),
        variant="narrow_vector_128b_safe_attempt",
    )
    guard_contract = build_guard_contract(effective_alignment)
    guard_contract_check = evaluate_guard_contract(guard_contract)

    can_integrate = bool(
        alignment_check["pass"]
        and effective_ptxas.get("status") == "parsed"
        and effective_ptxas.get("kernel_name") == wave9.PROBE_KERNEL
        and ptxas_resource_check["pass"]
        and runtime_check["pass"]
        and guard_contract_check["pass"]
    )
    blockers = _receipt_blockers(
        alignment_check=alignment_check,
        ptxas_ingest=effective_ptxas,
        ptxas_resource_check=ptxas_resource_check,
        runtime_check=runtime_check,
        guard_contract_check=guard_contract_check,
    )

    receipt = {
        "receipt": RECEIPT_NAME,
        "schema": SCHEMA,
        "status": (
            "pass_cute_integration_ready_vector_first"
            if can_integrate
            else "fail_cute_integration_blocked"
        ),
        "date": DATE,
        "branch": "worker/mamba3-mono-triton-model",
        "source_receipts": [
            "docs/status/mamba3_mono_wgmma_copy_path_wave8_receipt_2026_04_30.json",
            wave9.RECEIPT_PATH,
        ],
        "decision": {
            "vector_path_ready": can_integrate,
            "recommendation": (
                "integrate_vector_path_next"
                if can_integrate
                else "do_not_integrate_vector_path_until_blockers_clear"
            ),
            "tma_fallback": (
                "fallback_only_if_integrated_cute_lane_regresses_correctness_resources_or_timing"
                if can_integrate
                else "use_tma_descriptor_smoke_if_vector_blockers_are_structural"
            ),
            "summary": (
                "Integrate the 12-tile uint4 vector copy into the CuTe lane next; "
                "keep TMA as a fallback path, not the primary next step."
                if can_integrate
                else "Vector integration is blocked by the listed guard, runtime, or ptxas failures."
            ),
        },
        "blockers": blockers,
        "guard_contract": guard_contract,
        "checks": {
            "alignment_layout": {
                "status": alignment_check["status"],
                "pass": alignment_check["pass"],
                "tile_count": alignment_check.get("tile_count"),
                "tiles_covered": alignment_check.get("tiles_covered"),
                "failures": alignment_check["failures"],
            },
            "runtime_probe": {
                "status": runtime_check["status"],
                "pass": runtime_check["pass"],
                "failures": runtime_check["failures"],
            },
            "ptxas_resource": ptxas_resource_check,
            "guard_contract": guard_contract_check,
        },
        "source_evidence": _source_evidence(effective_runtime, effective_ptxas),
        "validation": {
            "generated_by": "tools/probes/mamba3_wgmma_wave10_copy_integration.py",
            "receipt": RECEIPT_PATH,
            "guide": GUIDE_PATH,
            "guard_header": GUARD_HEADER_PATH,
            "check_command": (
                "python tools/probes/mamba3_wgmma_wave10_copy_integration.py "
                f"--runtime-result {wave9.RUNTIME_RESULT_PATH} "
                f"--ptxas-ingest {wave9.PTXAS_INGEST_PATH} "
                f"--check {RECEIPT_PATH} "
                f"--check-guard-header {GUARD_HEADER_PATH} "
                f"--check-guide {GUIDE_PATH}"
            ),
            "write_command": (
                "python tools/probes/mamba3_wgmma_wave10_copy_integration.py "
                f"--runtime-result {wave9.RUNTIME_RESULT_PATH} "
                f"--ptxas-ingest {wave9.PTXAS_INGEST_PATH} "
                f"--write {RECEIPT_PATH} "
                f"--write-guard-header {GUARD_HEADER_PATH} "
                f"--write-guide {GUIDE_PATH}"
            ),
        },
    }
    _validate_receipt(receipt)
    return receipt


def _validate_receipt(receipt: dict[str, Any]) -> None:
    constants = receipt["guard_contract"]["constants"]
    assert constants["logical_tile_count"] == 12
    assert constants["vectors_per_chunk"] == 6144
    assert constants["dynamic_smem_bytes"] == 98304
    if receipt["decision"]["vector_path_ready"]:
        assert receipt["status"] == "pass_cute_integration_ready_vector_first"
        assert receipt["decision"]["recommendation"] == "integrate_vector_path_next"
        assert not receipt["blockers"]
    else:
        assert receipt["blockers"]


def render_markdown_guide(receipt: dict[str, Any]) -> str:
    evidence = receipt["source_evidence"]
    runtime = evidence["runtime"]
    timing = runtime.get("timing") or {}
    device = runtime.get("device") or {}
