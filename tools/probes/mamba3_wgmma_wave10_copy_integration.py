def _load_optional(path: pathlib.Path | None) -> dict[str, Any] | None:
    if path is None:
        return None
    return _read_json(path)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--runtime-result", type=pathlib.Path, default=None)
    parser.add_argument("--ptxas-ingest", type=pathlib.Path, default=None)
    parser.add_argument("--write", type=pathlib.Path, default=None)
    parser.add_argument("--check", type=pathlib.Path, default=None)
    parser.add_argument("--write-guard-header", type=pathlib.Path, default=None)
    parser.add_argument("--check-guard-header", type=pathlib.Path, default=None)
    parser.add_argument("--write-guide", type=pathlib.Path, default=None)
    parser.add_argument("--check-guide", type=pathlib.Path, default=None)
    args = parser.parse_args()

    runtime_result = _load_optional(args.runtime_result)
    ptxas_ingest = _load_optional(args.ptxas_ingest)
    receipt = build_receipt(runtime_result=runtime_result, ptxas_ingest=ptxas_ingest)
    rendered_receipt = _canonical(receipt)
    rendered_header = render_guard_header()
    rendered_guide = render_markdown_guide(receipt)

    if args.write_guard_header:
        _write_text(args.write_guard_header, rendered_header)
    if args.check_guard_header:
        if args.check_guard_header.read_text() != rendered_header:
            raise SystemExit(f"{args.check_guard_header} does not match generated guard header")

    if args.write_guide:
        _write_text(args.write_guide, rendered_guide)
    if args.check_guide:
        if args.check_guide.read_text() != rendered_guide:
            raise SystemExit(f"{args.check_guide} does not match generated guide")

    if args.write:
        _write_json(args.write, receipt)
    if args.check:
        if args.check.read_text() != rendered_receipt:
            raise SystemExit(f"{args.check} does not match generated receipt")
        return

    wrote_or_checked = any(
        (
            args.write,
            args.write_guard_header,
            args.check_guard_header,
            args.write_guide,
            args.check_guide,
        )
    )
    if not wrote_or_checked:
        print(rendered_receipt, end="")


if __name__ == "__main__":
    main()
